def build_shared_prefix(n_items: int = 16) -> str:
    """Системный промпт-«регламент», одинаковый для всех запросов сценария shared-prefix.

    16 пунктов — примерно 1,5–2 тыс. токенов у токенизатора Qwen2.5.
    """
    lines = [
        "Ты — ассистент регионального портала обращений граждан.",
        "Отвечай на вопросы пользователя, а если вопрос касается обращений, опирайся на регламент ниже.",
        "",
        "РЕГЛАМЕНТ РАССМОТРЕНИЯ ОБРАЩЕНИЙ",
    ]
    for i in range(1, n_items + 1):
        topic = _TOPICS[(i - 1) % len(_TOPICS)]
        lines.append(
            f"{i}. Обращения по теме «{topic}» регистрируются в день поступления и передаются "
            f"в ответственное ведомство не позднее {1 + i % 3} рабочих дней. Срок рассмотрения — "
            f"{10 + (i * 7) % 20} календарных дней, продление — не более чем на 30 дней с уведомлением "
            f"заявителя. Если в обращении нет адреса или описания проблемы, заявителю в течение "
            f"{2 + i % 4} дней направляется запрос на уточнение."
        )
    return "\n".join(lines)
